const DICTS: Record<ReplyLang, Dict> = { en, hi, kn, ta };

export function chromeLang(lang: UiLanguage): ReplyLang {
  return lang === "auto" ? "en" : lang;
}

export type Translate = (key: I18nKey, vars?: Record<string, string | number>) => string;

export function makeT(lang: UiLanguage): Translate {
  const dict = DICTS[chromeLang(lang)];
  return (key, vars) => {
    let s = dict[key] ?? en[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    }
    return s;
  };
}

/** Is this key one of ours? Used for dynamic keys like `at_${answerType}`. */
export function hasKey(key: string): key is I18nKey {
  return key in en;
}
